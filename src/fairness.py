"""Subgroup fairness audit of the retention model on the untouched test snapshot.

Groups (brief section 3.7): region, tenure band and spend quartile, plus one-time versus
repeat buyers, the largest gap in the earlier error analysis. For each group: size,
observed return rate, recall and precision of "will return", and selection rate (the
share scored at or above the decision threshold: the customers the assumed coupon policy
would select). A group is flagged when its recall is more than 5 percentage points below
overall recall. Every recall carries a Wilson 95% interval; a flag is "inconclusive"
when that interval still reaches the allowed range, which happens for small groups.

The groups are proxies built from behaviour and majority country. The data has no
protected characteristics, so this audit cannot establish demographic fairness.

Run ``python -m src.fairness`` after training. It loads the saved model (checksum
verified), recomputes the test probabilities, checks they equal test_predictions.parquet,
writes reports/current_run/fairness_audit.json and refreshes the generated tables in
governance/fairness_audit.md. Mitigation estimates use the June decision period, never
the test snapshot, so the holdout is not tuned on.
"""

from __future__ import annotations

import json
import math
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

import joblib
import numpy as np
import pandas as pd

from src.contracts import ARTIFACTS, FEATURE_NAMES, PROCESSED, PROJECT_ROOT
from src.generated_docs import replace_generated_block
from src.ingest import _sha256

REPORTS = PROJECT_ROOT / "reports" / "current_run"
AUDIT_DOC = PROJECT_ROOT / "governance" / "fairness_audit.md"
MAX_RECALL_GAP = 0.05  # brief: flag groups more than five percentage points below overall
DIMENSIONS = ["region", "tenure_band", "spend_quartile", "purchase_history"]

# Countries as spelled in the UCI workbook. Anything else known is "Rest of world".
EUROPE = {
    "Austria", "Belgium", "Channel Islands", "Cyprus", "Czech Republic", "Denmark", "EIRE",
    "Estonia", "European Community", "Finland", "France", "Germany", "Greece", "Iceland",
    "Italy", "Lithuania", "Malta", "Netherlands", "Norway", "Poland", "Portugal", "Spain",
    "Sweden", "Switzerland",
}  # fmt: skip
TENURE_BANDS = [(0, "under 6 months"), (183, "6-12 months"), (365, "12-18 months"),
                (548, "18 months or more")]  # fmt: skip
GENERATED_START = "<!-- BEGIN GENERATED BY python -m src.fairness -->"


def region_of(country: str | None) -> str:
    if country is None or country == "Unspecified":
        return "Unknown"
    if country == "United Kingdom":
        return "United Kingdom"
    return "Other Europe" if country in EUROPE else "Rest of world"


def tenure_band(days: float) -> str:
    label = TENURE_BANDS[0][1]
    for start, name in TENURE_BANDS:
        if days >= start:
            label = name
    return label


def assign_groups(X: pd.DataFrame, country_map: dict[str, int]) -> pd.DataFrame:
    """One label per dimension for every row; spend quartiles of the audited rows."""
    names = {code: name for name, code in country_map.items()}
    countries = X["country_code"].map(lambda code: names.get(int(code)))
    quartile = pd.qcut(X["monetary_total"], 4, labels=["Q1 (lowest)", "Q2", "Q3", "Q4 (highest)"])
    return pd.DataFrame(
        {
            "region": countries.map(region_of),
            "tenure_band": X["days_since_first_purchase"].map(tenure_band),
            "spend_quartile": quartile.astype(str),
            "purchase_history": np.where(X["is_one_time_buyer"] == 1, "one-time", "repeat"),
        },
        index=X.index,
    )


def wilson(successes: int, n: int, z: float = 1.96) -> tuple[float, float] | None:
    """Wilson score interval for a proportion; None when there is no denominator."""
    if n == 0:
        return None
    p = successes / n
    centre = (p + z * z / (2 * n)) / (1 + z * z / n)
    half = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / (1 + z * z / n)
    return max(0.0, centre - half), min(1.0, centre + half)


def rates(y: np.ndarray, selected: np.ndarray) -> dict[str, Any]:
    tp = int((y & selected).sum())
    returners, chosen = int(y.sum()), int(selected.sum())
    return {
        "n": len(y),
        "returners": returners,
        "return_rate": returners / len(y) if len(y) else None,
        "recall": tp / returners if returners else None,
        "recall_ci95": wilson(tp, returners),
        "precision": tp / chosen if chosen else None,
        "selection_rate": chosen / len(y) if len(y) else None,
    }


def audit(y: np.ndarray, p: np.ndarray, threshold: float, groups: pd.DataFrame) -> dict[str, Any]:
    """Overall and per-group rates with the brief's five-point recall flag."""
    y, selected = np.asarray(y).astype(bool), np.asarray(p) >= threshold
    overall = rates(y, selected)
    floor = overall["recall"] - MAX_RECALL_GAP
    result: dict[str, Any] = {"threshold": threshold, "overall": overall, "groups": {}}
    for dimension in DIMENSIONS:
        rows = []
        for name in sorted(groups[dimension].unique()):
            mask = (groups[dimension] == name).to_numpy()
            row = {"group": name, **rates(y[mask], selected[mask])}
            recall = row["recall"]
            row["recall_gap_pp"] = None if recall is None else 100 * (recall - overall["recall"])
            row["flagged"] = recall is not None and recall < floor
            row["evidence"] = None
            if row["flagged"]:
                # Strong when even the top of the 95% interval stays below the allowed range.
                strong = row["recall_ci95"][1] < floor
                row["evidence"] = "strong" if strong else "inconclusive (small group)"
            rows.append(row)
        result["groups"][dimension] = rows
    return result


def threshold_for_recall(y: np.ndarray, p: np.ndarray, target: float) -> float | None:
    """Highest threshold whose recall reaches *target* (fewest extra selections)."""
    y = np.asarray(y).astype(bool)
    if not y.any():
        return None
    for threshold in np.round(np.linspace(1, 0, 201), 3):
        if (y & (p >= threshold)).sum() / y.sum() >= target:
            return float(threshold)
    return 0.0


def mitigation_estimates(
    y: np.ndarray, p: np.ndarray, threshold: float, groups: pd.DataFrame, flagged: list[dict]
) -> list[dict[str, Any]]:
    """Group-specific thresholds that would close each flag, measured on development data."""
    y = np.asarray(y).astype(bool)
    floor = rates(y, p >= threshold)["recall"] - MAX_RECALL_GAP
    estimates = []
    for flag in flagged:
        mask = (groups[flag["dimension"]] == flag["group"]).to_numpy()
        if not y[mask].any():
            continue
        current = rates(y[mask], p[mask] >= threshold)
        lowered = threshold_for_recall(y[mask], p[mask], floor)
        after = rates(y[mask], p[mask] >= lowered) if lowered is not None else None
        estimates.append(
            {
                "dimension": flag["dimension"],
                "group": flag["group"],
                "decision_period_n": int(mask.sum()),
                "current_threshold": threshold,
                "threshold_reaching_overall_minus_5pp": lowered,
                "recall_before": current["recall"],
                "recall_after": after and after["recall"],
                "precision_before": current["precision"],
                "precision_after": after and after["precision"],
                "selection_rate_before": current["selection_rate"],
                "selection_rate_after": after and after["selection_rate"],
            }
        )
    return estimates


def flag_overlap(groups: pd.DataFrame, flagged: list[dict[str, Any]]) -> dict[str, Any]:
    """How far the flagged groups are the same customers (one-time buyers in each)."""
    one_time = (groups["purchase_history"] == "one-time").to_numpy()
    in_any = np.zeros(len(groups), dtype=bool)
    shares = {}
    for flag in flagged:
        mask = (groups[flag["dimension"]] == flag["group"]).to_numpy()
        in_any |= mask
        shares[f"{flag['dimension']}={flag['group']}"] = float(one_time[mask].mean())
    return {
        "rows_in_any_flagged_group": int(in_any.sum()),
        "share_of_rows": float(in_any.mean()) if len(groups) else 0.0,
        "one_time_buyer_share": shares,
    }


def _fmt(value: float | None) -> str:
    return "n/a" if value is None else f"{100 * value:.1f}%"


def markdown_tables(report: dict[str, Any]) -> str:
    overall = report["overall"]
    lines = [
        f"Test snapshot {report['test_cutoff']}, {overall['n']:,} rows, threshold "
        f"{report['threshold']:.2f}. Overall: recall {_fmt(overall['recall'])}, precision "
        f"{_fmt(overall['precision'])}, selection rate {_fmt(overall['selection_rate'])}. "
        f"Flag: recall below {_fmt(overall['recall'] - MAX_RECALL_GAP)}.",
    ]
    titles = {
        "region": "Region (majority country)",
        "tenure_band": "Tenure band (days since first purchase)",
        "spend_quartile": "Spend quartile (cumulative spend at the cut-off, audited rows)",
        "purchase_history": "Purchase history",
    }
    for dimension in DIMENSIONS:
        lines += [
            "",
            f"#### {titles[dimension]}",
            "",
            "| Group | Rows | Returners | Return rate | Recall (95% CI) | Precision "
            "| Selection rate | Recall gap | Flag |",
            "|---|---:|---:|---:|---|---:|---:|---:|---|",
        ]
        for row in report["groups"][dimension]:
            interval = row["recall_ci95"]
            recall = _fmt(row["recall"])
            if interval:
                recall += f" ({_fmt(interval[0])}–{_fmt(interval[1])})"
            gap = "n/a" if row["recall_gap_pp"] is None else f"{row['recall_gap_pp']:+.1f} pp"
            flag = row["evidence"] if row["flagged"] else ""
            lines.append(
                f"| {row['group']} | {row['n']:,} | {row['returners']:,} "
                f"| {_fmt(row['return_rate'])} | {recall} | {_fmt(row['precision'])} "
                f"| {_fmt(row['selection_rate'])} | {gap} | {flag} |"
            )
    overlap = report["overlap"]
    if overlap["one_time_buyer_share"]:
        shares = "; ".join(
            f"{group.split('=', 1)[1]} {_fmt(share)}"
            for group, share in overlap["one_time_buyer_share"].items()
        )
        lines += [
            "",
            f"Overlap: {overlap['rows_in_any_flagged_group']:,} of {overall['n']:,} rows "
            f"({_fmt(overlap['share_of_rows'])}) are in at least one flagged group. "
            f"Share of one-time buyers in each flagged group: {shares}.",
        ]
    if report["mitigation_estimates"]:
        lines += [
            "",
            "#### Group threshold needed to close each flag (June 2011 decision period)",
            "",
            "| Group | Rows | Threshold | Recall | Precision | Selection rate |",
            "|---|---:|---|---|---|---|",
        ]
        for m in report["mitigation_estimates"]:
            lowered = m["threshold_reaching_overall_minus_5pp"]
            lowered_text = "n/a" if lowered is None else f"{lowered:.3f}"
            lines.append(
                f"| {m['group']} | {m['decision_period_n']:,} "
                f"| {m['current_threshold']:.3f} → {lowered_text} "
                f"| {_fmt(m['recall_before'])} → {_fmt(m['recall_after'])} "
                f"| {_fmt(m['precision_before'])} → {_fmt(m['precision_after'])} "
                f"| {_fmt(m['selection_rate_before'])} → {_fmt(m['selection_rate_after'])} |"
            )
    return "\n".join(lines)


def _verified_model(directory: Path) -> tuple[Any, dict[str, Any]]:
    metadata = json.loads((directory / "retention_model_metadata.json").read_text())
    path = directory / "retention_model.joblib"
    if _sha256(path) != metadata["model_sha256"]:
        raise ValueError("Model checksum does not match metadata")
    return joblib.load(path), metadata  # trusted locally generated artifact


def run(artifacts: Path = ARTIFACTS, processed: Path = PROCESSED) -> dict[str, Any]:
    model, metadata = _verified_model(artifacts)
    X = pd.read_parquet(processed / "X.parquet")
    y = pd.read_parquet(processed / "y.parquet")["will_return"]
    snapshots = pd.read_parquet(processed / "snapshots.parquet")
    threshold = float(metadata["decision_threshold"])
    test = snapshots.index[snapshots["split"] == "test"]
    p_test = model.predict_proba(X.loc[test, FEATURE_NAMES])[:, 1]
    saved = pd.read_parquet(artifacts / "test_predictions.parquet")
    if (
        not np.allclose(saved["probability"], p_test)
        or not (saved["actual_will_return"].to_numpy() == y.loc[test].to_numpy()).all()
    ):
        raise ValueError("Recomputed test scores differ from test_predictions.parquet")
    test_groups = assign_groups(X.loc[test], metadata["country_map"])
    report = audit(y.loc[test].to_numpy(), p_test, threshold, test_groups)
    flagged = [
        {"dimension": dimension, **row}
        for dimension, rows in report["groups"].items()
        for row in rows
        if row["flagged"]
    ]
    report["overlap"] = flag_overlap(test_groups, flagged)
    decision = snapshots.index[snapshots["split"] == "decision"]
    report["mitigation_estimates"] = mitigation_estimates(
        y.loc[decision].to_numpy(),
        model.predict_proba(X.loc[decision, FEATURE_NAMES])[:, 1],
        threshold,
        assign_groups(X.loc[decision], metadata["country_map"]),
        flagged,
    )
    report.update(
        executed_at=datetime.now(UTC).isoformat(),
        test_cutoff=", ".join(sorted(snapshots.loc[test, "cutoff"].unique())),
        model_sha256=metadata["model_sha256"],
        flagged_groups=[f"{f['dimension']}={f['group']}" for f in flagged],
        positive_class="will_return",
        caveat="Proxy groups from behaviour and majority country; no protected attributes.",
    )
    return report


def main() -> None:
    report = run()
    (REPORTS / "fairness_audit.json").write_text(json.dumps(report, indent=2))
    replace_generated_block(AUDIT_DOC, GENERATED_START, markdown_tables(report))
    print(f"Flagged: {report['flagged_groups'] or 'none'}")


if __name__ == "__main__":
    main()
