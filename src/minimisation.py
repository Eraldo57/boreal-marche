"""Audit whether each currently served feature is necessary (brief section 3.7).

Necessity test (drop-column): refit the selected pipeline without one feature, using the
same hyperparameters, training rows and calibration method, and compare PR-AUC on the
June decision period against the full model. A paired bootstrap over decision-period
customers gives a 95% interval for the loss. A feature is "necessary" when the lower
bound is above zero; otherwise its contribution is not shown. Features that each look
unnecessary may carry the same information, so the whole candidate set is also removed
together and tested once more. The test snapshot is never used.

The audit recommends; it changes nothing. Removing features changes the model, the API
contract and every reported metric, so it needs a retrain and a human decision.

Run ``python -m src.minimisation`` after training. It writes
reports/current_run/minimisation_audit.json and refreshes the generated table in
governance/FEATURE_INVENTORY.md.
"""

from __future__ import annotations

import json
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

import joblib
import numpy as np
import pandas as pd
from sklearn.base import clone
from sklearn.calibration import CalibratedClassifierCV
from sklearn.frozen import FrozenEstimator
from sklearn.metrics import average_precision_score

from src.contracts import ARTIFACTS, FEATURE_NAMES, PROCESSED, PROJECT_ROOT
from src.generated_docs import replace_generated_block
from src.ingest import _sha256, load_config

REPORTS = PROJECT_ROOT / "reports" / "current_run"
INVENTORY_DOC = PROJECT_ROOT / "governance" / "FEATURE_INVENTORY.md"
GENERATED_START = "<!-- BEGIN GENERATED BY python -m src.minimisation -->"
BOOTSTRAP_DRAWS = 500
# Location features can stand in for nationality or residence; the rest describe purchases.
LOCATION_PROXIES = {"country_code", "is_domestic", "n_countries"}


def decision_probabilities(
    pipeline: Any,
    X: pd.DataFrame,
    y: pd.Series,
    splits: dict[str, pd.Index],
    columns: list[str],
    calibration_method: str,
) -> np.ndarray:
    """Refit like src.train (train + validation), calibrate, score the decision period."""
    fit_rows = splits["train"].append(splits["validation"])
    fitted = clone(pipeline).fit(X.loc[fit_rows, columns], y.loc[fit_rows])
    calibrated = CalibratedClassifierCV(FrozenEstimator(fitted), method=calibration_method)
    calibrated.fit(X.loc[splits["calibration"], columns], y.loc[splits["calibration"]])
    return np.asarray(calibrated.predict_proba(X.loc[splits["decision"], columns])[:, 1])


def paired_bootstrap_loss(
    y: np.ndarray, p_full: np.ndarray, p_without: np.ndarray, draws: list[np.ndarray]
) -> dict[str, float]:
    """PR-AUC of the full model minus the reduced one, with a 95% bootstrap interval."""
    losses = [
        average_precision_score(y[d], p_full[d]) - average_precision_score(y[d], p_without[d])
        for d in draws
    ]
    loss = average_precision_score(y, p_full) - average_precision_score(y, p_without)
    return {
        "pr_auc_loss": float(loss),
        "ci95_low": float(np.percentile(losses, 2.5)),
        "ci95_high": float(np.percentile(losses, 97.5)),
    }


def audit(
    pipeline: Any,
    X: pd.DataFrame,
    y: pd.Series,
    splits: dict[str, pd.Index],
    calibration_method: str,
    seed: int,
    draws: int = BOOTSTRAP_DRAWS,
) -> dict[str, Any]:
    features = list(X.columns)
    y_decision = y.loc[splits["decision"]].to_numpy()
    rng = np.random.default_rng(seed)
    samples = [rng.integers(0, len(y_decision), len(y_decision)) for _ in range(draws)]
    p_full = decision_probabilities(pipeline, X, y, splits, features, calibration_method)
    correlation = X.loc[splits["train"].append(splits["validation"])].corr(method="spearman")
    rows = []
    for feature in features:
        without = [f for f in features if f != feature]
        p = decision_probabilities(pipeline, X, y, splits, without, calibration_method)
        partner = correlation[feature].drop(feature).abs().idxmax()
        result = paired_bootstrap_loss(y_decision, p_full, p, samples)
        rows.append(
            {
                "feature": feature,
                **result,
                "necessary": result["ci95_low"] > 0,
                "closest_feature": partner,
                "abs_spearman": float(abs(correlation.loc[feature, partner])),
                "location_proxy": feature in LOCATION_PROXIES,
            }
        )
    candidates = [r["feature"] for r in rows if not r["necessary"]]
    joint: dict[str, Any] | None = None
    if candidates:
        kept = [f for f in features if f not in candidates]
        p = decision_probabilities(pipeline, X, y, splits, kept, calibration_method)
        joint = {
            "removed": candidates,
            "kept": kept,
            **paired_bootstrap_loss(y_decision, p_full, p, samples),
        }
        # Recommend only when the full model is not reliably better than the reduced one.
        joint["removal_recommended"] = joint["ci95_low"] <= 0
    return {
        "full_model_decision_pr_auc": float(average_precision_score(y_decision, p_full)),
        "bootstrap_draws": draws,
        "features": rows,
        "joint_removal": joint,
    }


def markdown_table(report: dict[str, Any]) -> str:
    lines = [
        f"Decision period {report['decision_cutoff']}, {report['decision_rows']:,} rows. "
        f"Full model PR-AUC {report['full_model_decision_pr_auc']:.4f}; "
        f"{report['bootstrap_draws']} paired bootstrap draws.",
        "",
        "| Feature | PR-AUC loss without it (95% CI) | Necessary? | Most correlated feature "
        "(\\|Spearman\\|) | Location proxy |",
        "|---|---|---|---|---|",
    ]
    for row in sorted(report["features"], key=lambda r: -r["pr_auc_loss"]):
        lines.append(
            f"| {row['feature']} | {row['pr_auc_loss']:+.4f} "
            f"({row['ci95_low']:+.4f} to {row['ci95_high']:+.4f}) "
            f"| {'yes' if row['necessary'] else 'not shown'} "
            f"| {row['closest_feature']} ({row['abs_spearman']:.2f}) "
            f"| {'yes' if row['location_proxy'] else ''} |"
        )
    joint = report["joint_removal"]
    if joint:
        verdict = (
            "the full model is not reliably better, so removal is recommended"
            if joint["removal_recommended"]
            else "the full model is reliably better, so this set should not all be removed"
        )
        lines += [
            "",
            f'Removing all {len(joint["removed"])} features marked "not shown" together: '
            f"PR-AUC loss {joint['pr_auc_loss']:+.4f} "
            f"({joint['ci95_low']:+.4f} to {joint['ci95_high']:+.4f}); {verdict}. "
            "A negative loss means the reduced model scored higher.",
        ]
    return "\n".join(lines)


def run(artifacts: Path = ARTIFACTS, processed: Path = PROCESSED) -> dict[str, Any]:
    metadata = json.loads((artifacts / "retention_model_metadata.json").read_text())
    path = artifacts / "retention_model.joblib"
    if _sha256(path) != metadata["model_sha256"]:
        raise ValueError("Model checksum does not match metadata")
    model = joblib.load(path)  # trusted locally generated artifact
    pipeline = model.estimator.estimator  # CalibratedClassifierCV(FrozenEstimator(pipeline))
    X = pd.read_parquet(processed / "X.parquet")[FEATURE_NAMES]
    y = pd.read_parquet(processed / "y.parquet")["will_return"]
    snapshots = pd.read_parquet(processed / "snapshots.parquet")
    splits = {
        name: snapshots.index[snapshots["split"] == name]
        for name in ["train", "validation", "calibration", "decision"]
    }
    seed = load_config()["data"]["seed"]
    report = audit(pipeline, X, y, splits, metadata["calibration_method"], seed)
    saved = model.predict_proba(X.loc[splits["decision"]])[:, 1]
    saved_pr_auc = average_precision_score(y.loc[splits["decision"]], saved)
    if not np.isclose(saved_pr_auc, report["full_model_decision_pr_auc"]):
        raise ValueError("Refitting does not reproduce the saved model; check the protocol")
    report.update(
        executed_at=datetime.now(UTC).isoformat(),
        model_sha256=metadata["model_sha256"],
        decision_cutoff=", ".join(sorted(snapshots.loc[splits["decision"], "cutoff"].unique())),
        decision_rows=len(splits["decision"]),
        note=(
            "Recommendation only for further removals. The original 13 unnecessary features "
            "were removed before this 12-feature model was trained (contract 2.0). "
            "Individual ablations do not justify jointly removing redundant signals."
        ),
    )
    return report


def main() -> None:
    report = run()
    (REPORTS / "minimisation_audit.json").write_text(json.dumps(report, indent=2))
    replace_generated_block(INVENTORY_DOC, GENERATED_START, markdown_table(report))
    joint = report["joint_removal"]
    print(f"Not shown necessary: {joint['removed'] if joint else 'none'}")


if __name__ == "__main__":
    main()
