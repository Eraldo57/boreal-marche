"""Generated blocks are rewritten in place; the hand-written text around them is kept."""

from __future__ import annotations

import pytest

from src.generated_docs import GENERATED_END, replace_generated_block

START = "<!-- BEGIN GENERATED BY a test -->"


def test_block_is_replaced_idempotently_and_surroundings_kept(tmp_path):
    doc = tmp_path / "doc.md"
    doc.write_text(f"Intro\n{START}\nSTALE-TABLES\n{GENERATED_END}\nOutro\n")
    for _ in range(2):
        replace_generated_block(doc, START, "| fresh | table |")
    assert doc.read_text() == f"Intro\n{START}\n| fresh | table |\n{GENERATED_END}\nOutro\n"


def test_block_content_with_backslashes_is_written_literally(tmp_path):
    doc = tmp_path / "doc.md"
    doc.write_text(f"{START}\n{GENERATED_END}")
    replace_generated_block(doc, START, r"\|Spearman\| \1")
    assert r"\|Spearman\| \1" in doc.read_text()


def test_missing_markers_raise(tmp_path):
    doc = tmp_path / "doc.md"
    doc.write_text("no markers here")
    with pytest.raises(ValueError, match="markers"):
        replace_generated_block(doc, START, "x")
